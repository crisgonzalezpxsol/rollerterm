import { contextBridge, ipcRenderer } from "electron";
import type { CalendarState, ChatStreamEvent, Reminder, MailState, MailThread, MenuCommand, ProdState, Session, RollertermApi, TicketsState, UsageState } from "../shared/types";

const api: RollertermApi = {
  createPty: (id, cwd, cols, rows) => ipcRenderer.invoke("pty:create", id, cwd, cols, rows),
  write: (id, data) => ipcRenderer.send("pty:write", id, data),
  resize: (id, cols, rows) => ipcRenderer.send("pty:resize", id, cols, rows),
  kill: (id) => ipcRenderer.send("pty:kill", id),
  getCwd: (id) => ipcRenderer.invoke("pty:cwd", id),
  pickFolder: (defaultPath) => ipcRenderer.invoke("dialog:folder", defaultPath),
  loadSession: () => ipcRenderer.invoke("session:load"),
  saveSession: (session: Session) => ipcRenderer.invoke("session:save", session),
  onData: (cb) => ipcRenderer.on("pty:data", (_e, id: string, data: string) => cb(id, data)),
  onExit: (cb) => ipcRenderer.on("pty:exit", (_e, id: string, code: number) => cb(id, code)),
  onMenu: (cb) => ipcRenderer.on("menu", (_e, cmd: MenuCommand) => cb(cmd)),
  getCalendar: () => ipcRenderer.invoke("calendar:get"),
  refreshCalendar: () => ipcRenderer.send("calendar:refresh"),
  onCalendar: (cb) => ipcRenderer.on("calendar:state", (_e, state: CalendarState) => cb(state)),
  getMail: () => ipcRenderer.invoke("mail:get"),
  refreshMail: () => ipcRenderer.send("mail:refresh"),
  summarizeMail: () => ipcRenderer.send("mail:summarize"),
  setMailLists: (vip, blocked) => ipcRenderer.send("mail:lists", vip, blocked),
  onMail: (cb) => ipcRenderer.on("mail:state", (_e, state: MailState) => cb(state)),
  getSettings: () => ipcRenderer.invoke("settings:get"),
  setSettings: (patch) => ipcRenderer.invoke("settings:set", patch),
  listBrowsers: () => ipcRenderer.invoke("settings:browsers"),
  testBrowser: () => ipcRenderer.send("settings:test-browser"),
  chatList: () => ipcRenderer.invoke("chat:list"),
  chatNew: () => ipcRenderer.invoke("chat:new"),
  chatRename: (convId, title) => ipcRenderer.invoke("chat:rename", convId, title),
  chatDelete: (convId) => ipcRenderer.invoke("chat:delete", convId),
  chatHistory: (convId) => ipcRenderer.invoke("chat:history", convId),
  chatSend: (convId, text) => ipcRenderer.invoke("chat:send", convId, text),
  chatStop: (convId) => ipcRenderer.send("chat:stop", convId),
  chatApprove: (id, approved) => ipcRenderer.send("chat:approve", id, approved),
  onChat: (cb) => ipcRenderer.on("chat:event", (_e, event: ChatStreamEvent) => cb(event)),
  onNotesChanged: (cb) => ipcRenderer.on("notes:changed", () => cb()),
  onReminder: (cb) => ipcRenderer.on("reminder:fire", (_e, r: Reminder) => cb(r)),
  listNotes: () => ipcRenderer.invoke("notes:list"),
  saveNote: (note) => ipcRenderer.invoke("notes:save", note),
  deleteNote: (id) => ipcRenderer.invoke("notes:delete", id),
  listReminders: () => ipcRenderer.invoke("reminders:list"),
  addReminder: (when, text, noteId) => ipcRenderer.invoke("reminders:add", when, text, noteId),
  removeReminder: (id) => ipcRenderer.invoke("reminders:remove", id),
  onRemindersChanged: (cb) => ipcRenderer.on("reminders:changed", () => cb()),
  exportConfig: (ui) => ipcRenderer.invoke("config:export", ui),
  importConfig: () => ipcRenderer.invoke("config:import"),
  getTickets: () => ipcRenderer.invoke("tickets:get"),
  refreshTickets: () => ipcRenderer.send("tickets:refresh"),
  viewTicket: (numero) => ipcRenderer.invoke("tickets:view", numero),
  ticketAction: (numero, action) => ipcRenderer.invoke("tickets:action", numero, action),
  onTickets: (cb) => ipcRenderer.on("tickets:state", (_e, state: TicketsState) => cb(state)),
  listMcpServers: () => ipcRenderer.invoke("tickets:servers"),
  getProd: () => ipcRenderer.invoke("prod:get"),
  refreshProd: () => ipcRenderer.send("prod:refresh"),
  onProd: (cb) => ipcRenderer.on("prod:state", (_e, state: ProdState) => cb(state)),
  listRailwayProjects: () => ipcRenderer.invoke("prod:projects"),
  getUsage: () => ipcRenderer.invoke("usage:get"),
  refreshUsage: () => ipcRenderer.send("usage:refresh"),
  onUsage: (cb) => ipcRenderer.on("usage:state", (_e, state: UsageState) => cb(state)),
  onNewMail: (cb) => ipcRenderer.on("mail:new", (_e, threads: MailThread[]) => cb(threads)),
};

contextBridge.exposeInMainWorld("rollerterm", api);
